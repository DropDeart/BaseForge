/// <summary>
/// auth.yaml <c>userProfile</c>'dan Identity'nin profil kodunu üretir: <c>ApplicationUser</c> partial'ı (alanlar +
/// enum'lar), <c>UserProfile</c> (metadata, okuma/yazma, claim, proto eşlemesi, EF yapılandırması, şema senkronu) ve
