    /// <summary>EF Core (Npgsql) varsayılan eşlemesiyle aynı kolon tipi.</summary>
    private static string ColumnType(Field f) => f.Type switch
    {
        "string" or "text" => f.Spec.MaxLength is { } max ? $"character varying({max.ToString(CultureInfo.InvariantCulture)})" : "text",
        "enum" => "text",
        "int" => "integer",
        "long" => "bigint",
        "short" => "smallint",
        "decimal" => "numeric",
        "double" => "double precision",
        "float" => "real",
        "bool" => "boolean",
        "datetime" => "timestamp with time zone",
        "date" => "date",
        "guid" or "uuid" => "uuid",
        _ => "text",
    };

    /// <summary>NOT NULL kolonlar için mevcut satırları geçerli tutan DEFAULT; nullable'larda boş.</summary>
    private static string ColumnConstraint(Field f)
    {
        if (f.Spec.Nullable)
        {
            return string.Empty;
        }

        var literal = f.Type switch
        {
            "string" or "text" => SqlString(f.Spec.Default ?? string.Empty),
            "enum" => SqlString(f.Spec.Default ?? f.Spec.Values[0]),
            "int" or "long" or "short" or "decimal" or "double" or "float" => f.Spec.Default ?? "0",
            "bool" => (f.Spec.Default ?? "false").ToLowerInvariant(),
            "datetime" => "'0001-01-01 00:00:00+00'",
            "date" => "'0001-01-01'",
            "guid" or "uuid" => "'00000000-0000-0000-0000-000000000000'",
            _ => "''",
        };

        return $" NOT NULL DEFAULT {literal}";
    }

    private static string SqlString(string value) => "'" + value.Replace("'", "''", StringComparison.Ordinal) + "'";

    private static string Quote(string value) =>
        "\"" + value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";

    private static string CSharpVerbatim(string value) => "@\"" + value.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";

    private static string Bool(bool value) => value ? "true" : "false";
