    /// <summary><c>UserMessage</c>'ın sabit alanlarından sonraki ilk proto alan numarası (1–4: id, user_name, email, full_name).</summary>
    private const int FirstProfileProtoNumber = 5;

    private sealed record Field(string Name, string Camel, PropSpec Spec, string Type, bool IsEnum, string EnumType);

    private static List<Field> Fields(UserProfileSpec? profile) =>
        (profile?.Props ?? [])
            .Select(kv =>
            {
                var name = NameUtil.Pascal(kv.Key);
                var type = kv.Value.Type.Trim().ToLowerInvariant();
                return new Field(name, NameUtil.Camel(name), kv.Value, type, TypeMap.IsEnum(type), TypeMap.EnumTypeName("User", name));
            })
            .ToList();

    /// <summary><c>identity/User</c> tüketicilerinin zengin <c>UserReference</c>'ı için sabit + profil proto alanları.</summary>
    public static List<ProtoFieldModel> ConsumerProtoFields(UserProfileSpec? profile)
    {
        var fields = new List<ProtoFieldModel>
        {
            CodeGenerator.MakeProtoField("UserName", "string", 2),
            CodeGenerator.MakeProtoField("Email", "string", 3),
            CodeGenerator.MakeProtoField("FullName", "string", 4),
        };

        var number = FirstProfileProtoNumber;
        foreach (var f in Fields(profile))
        {
            fields.Add(CodeGenerator.MakeProtoField(f.Name, f.Type, number++, f.Spec.Nullable));
        }

        return fields;
    }

